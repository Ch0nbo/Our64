"""Writes player/source/gamedb.c from mupen64plus's ROM catalogue (mupen64plus.ini,
part of mupen64plus-core, GPL): for each ROM by its header CRCs, whether the game
uses a Rumble Pak, whether it saves to a Controller Pak, whether it takes a
Transfer Pak, and its CountPerOp
(counter factor). Our64 picks each player's Pak from it (Zach, 2026-10-16:
players never choose a Pak) and runs the game at its counter factor.

    python3 -I tools/make-gamedb.py <mupen64plus.ini> > player/source/gamedb.c
"""
import re, sys

entries, cur = {}, None
for line in open(sys.argv[1], encoding="utf-8", errors="replace"):
    line = line.strip()
    m = re.match(r"^\[([0-9A-Fa-f]{32})\]$", line)
    if m:
        cur = entries.setdefault(m.group(1).upper(), {})
        continue
    if cur is None or "=" not in line or line.startswith(";"):
        continue
    k, v = line.split("=", 1)
    cur[k.strip()] = v.strip()

def field(e, k, seen=()):
    if k in e:
        return e[k]
    ref = e.get("RefMD5", "").upper()
    if ref in entries and ref not in seen:
        return field(entries[ref], k, seen + (ref,))
    return None

rows, cpos = {}, {}
for md5, e in entries.items():
    crc = field(e, "CRC")
    if not crc:
        continue
    a, b = crc.split()
    flags = (1 if field(e, "Rumble") == "Yes" else 0) | (2 if field(e, "Mempak") == "Yes" else 0) \
        | (4 if field(e, "Transferpak") == "Yes" else 0)
    key = (int(a, 16), int(b, 16))
    rows[key] = rows.get(key, 0) | flags
    cpo = field(e, "CountPerOp")
    if cpo and cpo.isdigit() and 1 <= int(cpo) <= 4:
        cpos[key] = int(cpo)

# Releases mupen64plus.ini lists without Paks or a factor while another
# release of the same game (the same cartridge ID) has them: they take that
# release's. Found by reading every No-Intro N64 ROM's header (2026-11-02).
TWINS = (
    ((0x861C3519, 0xF6091CE5), (0x07861842, 0xA12EBC9F)),  # Excitebike 64 (J) from (U)
    ((0x0AA0055B, 0x7637DF65), (0xFBB9F1FA, 0x6BF88689)),  # Daffy Duck Starring as Duck Dodgers (E) from Duck Dodgers (U)
    ((0x74E87A70, 0x6293AED4), (0x0B6B4DDB, 0x9671E682)),  # Roadsters (E) from (U)
    ((0x0375CF67, 0x56A93FAA), (0x0ADAECA7, 0xB17F9795)),  # Ogre Battle 64 (J) (Rev 1) from (U) (Rev 1)
)
for missing, twin in TWINS:
    if not rows.get(missing) and rows.get(twin):
        rows[missing] = rows[twin]
    if not cpos.get(missing) and cpos.get(twin):
        cpos[missing] = cpos[twin]

keys = sorted(k for k in set(rows) | set(cpos) if rows.get(k) or cpos.get(k))
print("/* Generated by tools/make-gamedb.py from mupen64plus.ini (mupen64plus-core, GPL).")
print(" * Each ROM by its header CRC1 and CRC2: Paks (1 uses a Rumble Pak, 2 saves to a Controller Pak,")
print(" * 4 takes a Transfer Pak)")
print(" * and CountPerOp (0: not listed).")
print(" * Games not listed use neither Pak. Do not edit: run the tool again. */")
print('#include "gamedb.h"\n')
print("static const struct { uint32_t crc1, crc2; uint8_t paks, count_per_op; } g_games[] = {")
for a, b in keys:
    print("\t{ 0x%08X, 0x%08X, %d, %d }," % (a, b, rows.get((a, b), 0), cpos.get((a, b), 0)))
print("};\n")
print("""static int find(uint32_t crc1, uint32_t crc2)
{
	int lo = 0, hi = (int)(sizeof(g_games) / sizeof(g_games[0])) - 1;
	while (lo <= hi) {
		int mid = (lo + hi) / 2;
		if (g_games[mid].crc1 == crc1 && g_games[mid].crc2 == crc2)
			return mid;
		if (g_games[mid].crc1 < crc1 || (g_games[mid].crc1 == crc1 && g_games[mid].crc2 < crc2))
			lo = mid + 1;
		else
			hi = mid - 1;
	}
	return -1;
}

int gamedb_paks(uint32_t crc1, uint32_t crc2)
{
	int i = find(crc1, crc2);
	return i < 0 ? 0 : g_games[i].paks;
}

int gamedb_count_per_op(uint32_t crc1, uint32_t crc2)
{
	int i = find(crc1, crc2);
	return i < 0 ? 0 : g_games[i].count_per_op;
}

int gamedb_pak_for(int paks)
{
	return paks & GAMEDB_RUMBLE ? PAK_RUMBLE : PAK_CONTROLLER;
}""")
print("// %d games" % len(keys), file=sys.stderr)
